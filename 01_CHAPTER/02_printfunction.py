# complete syntax of print() function  ----->
# print(object, sep=' ', end='\n', file=sys.stdout, flush=False)

# Parameters:
# object → The value(s) you want to print. You can pass multiple values separated by commas.
# sep (default = ' ') → Separator between multiple values.
# end (default = '\n') → String appended after the last value. By default, it adds a new line.
# file → Where to send the output (default is console).
# flush (default = False) → If True, the output is flushed immediately.

